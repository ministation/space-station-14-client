        if (name.Length == 0) continue;
        var full = string.IsNullOrEmpty(ns) ? name : ns + "." + name;
        existing.Add(full);
        if (Regex.IsMatch(text, @"class\s+" + Regex.Escape(name) + @"\s*<"))
            existing.Add(full + "`1");
    }
}
