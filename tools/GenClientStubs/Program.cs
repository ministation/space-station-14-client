static bool LooksLikeEnum(string name) =>
    name is "MidiRendererStatus" or "PhysicsDebugFlags" or "AccessLevel" or "DebugMonitor"
        or "KeyBindingType" or "KeyEventType" or "ScreenshotType" or "DrawPrimitiveTopology"
        or "RenderTargetColorFormat" or "RadioOptionsLayout" or "ClientRunLevel";

static (string Name, int Arity) ParseArity(string simple)
{
    var tick = simple.IndexOf('`');
    if (tick < 0) return (simple, 0);
    return (simple[..tick], int.Parse(simple[(tick + 1)..]));
}

static string TypeParams(int arity)
{
    if (arity <= 0) return "";
    return "<" + string.Join(", ", Enumerable.Range(1, arity).Select(i => "T" + (arity == 1 ? "" : i.ToString()))) + ">";
}

static void EmitClass(StringBuilder sb, string name, int arity, string bases,
    bool abstractClass = false, bool sealedClass = false)
{
    var mods = abstractClass ? "abstract " : sealedClass ? "sealed " : "";
    sb.Append("    public ").Append(mods).Append("class ").Append(name).Append(TypeParams(arity));
    if (!string.IsNullOrEmpty(bases)) sb.Append(' ').Append(bases);
    sb.AppendLine();
    sb.AppendLine("    {");
    sb.AppendLine("    }");
}

static void EmitInterface(StringBuilder sb, string name, int arity)
{
    sb.Append("    public interface ").Append(name).Append(TypeParams(arity)).AppendLine();
    sb.AppendLine("    {");
    sb.AppendLine("    }");
}

static void EmitDelegate(StringBuilder sb, string name, int arity)
{
    sb.Append("    public delegate void ").Append(name).Append(TypeParams(arity))
        .AppendLine("(object? sender, EventArgs e);");
}
