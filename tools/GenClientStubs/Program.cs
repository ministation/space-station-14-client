static bool HasType(HashSet<string> existing, string full)
{
    if (existing.Contains(full)) return true;
    // VisualizerSystem`1 vs VisualizerSystem`1 / VisualizerSystem
    var tick = full.IndexOf('`');
    if (tick > 0)
    {
        var bare = full[..tick];
        if (existing.Any(e => e == bare || e.StartsWith(bare + "`", StringComparison.Ordinal)))
            return true;
    }
    return existing.Any(e => e.StartsWith(full + "`", StringComparison.Ordinal));
}

static string FullNs(string full)
{
    var i = full.LastIndexOf('.');
    return i < 0 ? "" : full[..i];
}

static string SimpleName(string full)
{
    var i = full.LastIndexOf('.');
    return i < 0 ? full : full[(i + 1)..];
}

static void EmitType(StringBuilder sb, string ns, string simple, string full)
{
    // Handled in dedicated source files — skip duplicates for critical shells.
    if (full is "Robust.Client.GameObjects.VisualizerSystem`1"
        or "Robust.Client.GameObjects.AppearanceSystem"
        or "Robust.Client.GameObjects.AppearanceChangeEvent"
        or "Robust.Client.GameObjects.AnimationPlayerSystem"
        or "Robust.Client.GameObjects.AnimationPlayerComponent"
        or "Robust.Client.GameObjects.AnimationCompletedEvent"
        or "Robust.Client.GameObjects.SpriteSystem"
        or "Robust.Client.GameObjects.SpriteComponent"
        or "Robust.Client.UserInterface.CustomControls.DefaultWindow"
        or "Robust.Client.UserInterface.Controllers.UIController")
    {
        sb.AppendLine($"    // (hand-written) {simple}");
        return;
    }

    var (name, arity) = ParseArity(simple);

    if (name.EndsWith("Attribute", StringComparison.Ordinal))
    {
        EmitClass(sb, name, arity, ": Attribute", sealedClass: true);
        return;
    }

    // Interfaces before Controls — e.g. IViewportControl lives under CustomControls.
    if (name.StartsWith('I') && name.Length > 1 && char.IsUpper(name[1]))
    {
        EmitInterface(sb, name, arity);
        return;
    }

    if (full.Contains(".Controls.", StringComparison.Ordinal)
        || full.Contains(".CustomControls.", StringComparison.Ordinal))
    {
        var baseType = GuessControlBase(ns, name);
        EmitClass(sb, name, arity, baseType is null ? "" : ": " + baseType);
        return;
    }

    if (name.EndsWith("Delegate", StringComparison.Ordinal) || full.Contains("CopyPixelsDelegate", StringComparison.Ordinal))
    {
        EmitDelegate(sb, name, arity);
        return;
    }

    if (LooksLikeEnum(name))
    {
        sb.Append("    public enum ").Append(name).AppendLine(" : byte");
        sb.AppendLine("    {");
        sb.AppendLine("        None = 0,");
        sb.AppendLine("    }");
        return;
    }

    if (name.EndsWith("Event", StringComparison.Ordinal)
        || name.EndsWith("EventArgs", StringComparison.Ordinal))
    {
        EmitClass(sb, name, arity, name.EndsWith("EventArgs", StringComparison.Ordinal) ? ": EventArgs" : "");
        return;
    }

    if (name.EndsWith("Component", StringComparison.Ordinal))
    {
        EmitClass(sb, name, arity, ": global::Robust.Shared.GameObjects.Component");
        return;
    }

    if (name.EndsWith("System", StringComparison.Ordinal)
        && (ns.Contains("GameObjects", StringComparison.Ordinal)
            || ns.Contains("Audio", StringComparison.Ordinal)
            || ns.Contains("Physics", StringComparison.Ordinal)
            || ns.Contains("Debugging", StringComparison.Ordinal)
            || ns.Contains("ComponentTrees", StringComparison.Ordinal)))
    {
        EmitClass(sb, name, arity, ": global::Robust.Shared.GameObjects.EntitySystem");
        return;
    }

    if (name is "Overlay")
    {
        // Already defined in hand-written Graphics/Overlay stubs.
        sb.AppendLine("    // (hand-written) Overlay");
        return;
    }

    if (name is "GridOverlay")
    {
        EmitClass(sb, name, arity, ": global::Robust.Client.Graphics.Overlay");
        return;
    }

    if (name is "State")
    {
        sb.AppendLine("    // (hand-written) State");
        return;
    }

    if (name is "UIScreen")
    {
        EmitClass(sb, name, arity, ": global::Robust.Client.UserInterface.Control");
        return;
    }

    if (name is "ClientRunLevel")
    {
        sb.AppendLine("    // (hand-written) ClientRunLevel");
        return;
    }

    if (name is "PlacementMode" or "PlacementHijack")
    {
        EmitClass(sb, name, arity, "", abstractClass: true);
        return;
    }

    if (name is "BaseReplayCommand" or "LoadReplayJob" or "AnimationTrackProperty")
    {
        EmitClass(sb, name, arity, "", abstractClass: true);
        return;
    }

    EmitClass(sb, name, arity, "");
}

